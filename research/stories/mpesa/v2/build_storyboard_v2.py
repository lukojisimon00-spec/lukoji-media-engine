def build() -> dict:
    seq_sent = {s["id"]: sentences(s["voix_off"]) for s in SCRIPT["sequences"]}
    used = {k: 0 for k in seq_sent}
    scenes = []
    for i, sp in enumerate(SPEC, 1):
        (seq, n, typ, auth, mention, desc, sujet, compo, cadrage, cam, graph, txt, res, amb, fx, trans, montage,
         intention, risques, faisab, duree) = sp
        start = used[seq]
        vo = " ".join(seq_sent[seq][start:start + n])
        used[seq] = start + n
        statuts = sorted({RES[r]["statut"] for r in res})
        sc = {"id": f"SC-{i:02d}", "sequence": seq, "voix_off": vo, "intention": intention, "type_visuel": typ,
              "authenticite": auth, "description": desc, "sujet": sujet, "composition": compo, "cadrage": cadrage,
              "mouvement_camera": cam, "mouvement_graphique": graph, "animation": [graph] if graph != "aucun" else [],
              "texte_ecran": txt, "ressources": res, "statut_ressource": statuts,
              "sources_visuelles": [RES[r].get("page") or RES[r].get("url_directe") or RES[r]["description"] for r in res],
              "ambiance": amb, "effets_sonores": fx, "transition": trans, "instructions_montage": montage,
              "raison_narrative": intention, "risques_representation": risques or "Aucun risque particulier identifié.",
              "faisabilite": faisab}
        if mention:
            sc["mention_ecran"] = mention
        if duree:
            sc["duree_s"] = duree
        scenes.append(sc)
    for k, s in seq_sent.items():
        if used[k] != len(s):
            raise SystemExit(f"{k} : {used[k]} phrases utilisées sur {len(s)}")
    return {"version_editoriale": "v2 — reconstruit (audit humain 70d0f17)", "scenes": scenes}


if __name__ == "__main__":
    out = HERE / "storyboard_v2.json"
    doc = build()
    out.write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{out} : {len(doc['scenes'])} scènes")
